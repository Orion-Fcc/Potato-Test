"""数据隔离：让"环境里已有的数据"不再被误判成缺陷。

## 问题（本项目实测，不是理论）

抽样同一条用例的多次运行，判定里提到的记录数在变：

```
case 2「查询：使用范围=场地资源」
  #2   passed  "结果仅包含 4 条场地资源规则"
  #176 failed  "结果仍显示共 11 条记录且存在多页"
  #177 passed  "结果共 5 条"
```

用户最初的问题是"同一个用例两次结果不一样"。追下去发现**同一个用例内部**也不一样，
而它的预期写的是"结果只含使用范围命中场地资源的规则"—— 判定的 4/5/11 条数说明
**列表里本来就有 11 条规则**（前面 14 条新增类用例跑完留下的），筛选只该筛出其中一部分。

真正会假失败的是**预期里写死了数字**的那批。实测扫出 12 条，例如：

```
case 14「聚合展示」   预期"该规则只占 1 行"   → 第二次跑那条规则还在，就是 2 行
case 45「新增：正常填写后保存」  预期"列表中存在 1 行 SIT手测-场地结算"
case 62「业务后果」    预期"核对列表两行金额"
```

这些用例**第一次跑是对的，第二次跑必然失败** —— 不是产品有 bug，是它自己上次留下的
数据污染了自己的前置条件。这叫**自污染**：测试自己制造了让后续（以及自己下次）失败的脏数据。

## 两条可选的处置方向

1. **让用例可重复跑**：预期不写死绝对数字（改成"至少 1 条""包含名称为 X 的那一行"），
   或者用例自己清理上次留下的数据。
2. **承认它不可重复**：有些用例本质是一次性的（新建 → 核对 → 删除），那就明确写成
   "只跑一次"，并在名字/标签上标出来，别混进"每次都跑"的集合里。

**这是业务判断，不该由工具替用户决定。** 所以这个模块只做一件事：
把"环境数据可能不是干净基线"这件事**明确告诉 agent**，让它不要把脏数据当成缺陷，
也不要因为条数对不上就自行判失败。

## 注入的规则

拼在任务提示末尾（`build_task`），只在用例作者显式写了 data_hygiene 时注入 ——
不默认注入，否则会给每个用例都塞一段与它无关的话。
"""

from __future__ import annotations

# 供用例作者直接复用的默认文案。写进用例的 data_hygiene 字段即可生效。
DEFAULT_DATA_HYGIENE = (
    "注意：环境里可能已经存在其他用例运行留下的数据（新增的规则、已改过的名称等）。"
    "请遵守以下约定：\n"
    "1. **不要把环境里已有的数据当成缺陷**。它可能是之前某次运行的残留，不是本次功能的问题。\n"
    "2. **不要以『列表里总共有几条』作为判断依据** —— 总数会被其他用例改变。"
    "只看你自己这次创建的那一条（或按名称/条件筛选出的那部分）是否符合预期。\n"
    "3. 如果你自己这次创建的数据与上次运行留下的重名，**先清理掉旧的那条再继续**，"
    "否则你无法区分新旧。\n"
    "4. 如果你的核对目标依赖某条特定数据存在，而它现在不存在，"
    "**如实说明「缺少核对所需的前置数据」并停下**，不要凭空造一条来凑，也不要直接判失败。"
)


def render(data_hygiene: str | None) -> str:
    """把用例作者的 data_hygiene 渲染成注入文本。空/空白则不注入。"""
    text = (data_hygiene or "").strip()
    if not text:
        return ""
    return text
